-- ── Busca sem acento ────────────────────────────────────────
-- A TACO escreve "Pão, trigo, francês". Quem busca digita "pao frances".
-- `nome_busca` guarda o nome em minúsculas, sem acento e sem pontuação;
-- o app normaliza o termo do mesmo jeito e procura palavra por palavra.
create extension if not exists unaccent with schema extensions;

alter table public.alimentos add column if not exists nome_busca text;

-- `search_path` com os dois schemas: dependendo de quando o projeto foi
-- criado, o Supabase instalou `unaccent` em `public` ou em `extensions`.
create or replace function public.alimento_nome_busca(nome text)
returns text
language sql immutable set search_path = public, extensions as $$
  select btrim(regexp_replace(lower(unaccent(coalesce(nome, ''))), '[^a-z0-9]+', ' ', 'g'));
$$;

create or replace function public.alimentos_preenche_busca()
returns trigger
language plpgsql set search_path = public as $$
begin
  new.nome_busca := public.alimento_nome_busca(new.nome);
  return new;
end;
$$;

drop trigger if exists alimentos_busca on public.alimentos;
create trigger alimentos_busca before insert or update of nome
  on public.alimentos for each row execute function public.alimentos_preenche_busca();

update public.alimentos set nome_busca = public.alimento_nome_busca(nome)
 where nome_busca is distinct from public.alimento_nome_busca(nome);

-- ── Sai a base aproximada ───────────────────────────────────
-- Só o que nenhum plano e nenhuma receita usa: as duas tabelas
-- referenciam alimentos com `on delete restrict`, e o plano já entregue
-- tem de continuar fechando a conta. Ficam também os suplementos (a TACO
-- não tem whey nem creatina) e os leites fluidos (ver acima).
delete from public.alimentos a
 where a.fonte = 'seed_inicial'
   and a.grupo is distinct from 'Suplementos'
   and a.codigo_origem not in ('s050', 's051')
   and not exists (select 1 from public.refeicao_itens i where i.alimento_id = a.id)
   and not exists (select 1 from public.receita_ingredientes r where r.alimento_id = a.id);

-- O que sobrou da base antiga passa para os grupos da TACO, para a busca
-- não mostrar "Frutas" e "Frutas e derivados" lado a lado.
update public.alimentos set grupo = case
    when codigo_origem in ('s036', 's037') then 'Ovos'
    when codigo_origem in ('s083', 's084', 's085', 's086') then 'Castanhas e sementes'
    when grupo = 'Cereais e massas' then 'Cereais e derivados'
    when grupo = 'Carnes e ovos' then 'Carnes'
    when grupo = 'Pescados' then 'Peixes e frutos do mar'
    when grupo = 'Verduras e legumes' then 'Verduras e hortaliças'
    when grupo = 'Gorduras' then 'Gorduras e óleos'
    when grupo = 'Açúcares' then 'Açúcares e doces'
    else grupo
  end
 where fonte = 'seed_inicial';

